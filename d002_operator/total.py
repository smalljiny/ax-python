'''
설명

아이스크림 가게를 운영하는 철수는 오늘 판매한 아이스크림의 총 매출을 계산하려고 합니다.
가게에서는 다음과 같은 아이스크림을 판매하고 있습니다.

메로나: 1개에 500원
빵또아: 1개에 1,000원
월드콘: 1개에 2,500원
오늘 판매한 메로나, 빵또아, 월드콘의 개수가 각각 주어질 때,
세 종류의 아이스크림을 판매하여 얻은 총 매출액을 계산하는 프로그램을 작성하세요.

입력

순서는 메로나, 빵또아, 월드콘 순입니다.
종류별로 아이스크림의 개수를 가로로 입력받으시오.
각 아이스크림의 개수는 0 이상의 정수입니다.
출력

오늘 판매한 아이스크림의 총 매출액을 출력하세요.
'''

melon, bbang, world = map(int, input().split())

total = melon * 500 + bbang * 1000 + world * 2500

print(total)