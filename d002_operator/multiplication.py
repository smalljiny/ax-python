'''
설명

세자리 수 x 세자리 수의 결과는 다음과 같이 이루어진다.

image.png

(1)과 (2)위치에 들어갈 세 자리 자연 수가 주어질 때 (3), (4), (5), (6)위치에 들어갈 값을 구하는 프로그램을 작성하시오.

입력

첫번째 줄에 (1)의 위치에 들어갈 세 자리 자연수가, 두번째 줄에 (2)의 위치에 들어갈 세자리 자연수가 주어진다.

출력

첫째 줄부터 넷째 줄까지 차례대로 (3), (4), (5), (6)에 들어갈 값을 출력한다.
'''

N = int(input())
M = int(input())

d0 = M % 10
d1 = (M % 100) // 10
d2 = M // 100

n3 = N * d0
n4 = N * d1
n5 = N * d2
n6 = N * M

print(n3)
print(n4)
print(n5)
print(n6)