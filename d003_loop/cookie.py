'''
설명

완벽주의 반장 영수는 총 n개의 쿠키를 친구들에게 나누어 주려고 합니다.
쿠키를 한 개도 남기지 않고 모든 친구가 같은 개수만큼 나눌 수 있는 경우에만 쿠키를 나누어 먹고 싶습니다.

쿠키의 개수 n이 주어졌을 때, 쿠키를 똑같이 나누어 가질 수 있는 모든 인원 수를 오름차순으로 출력하는 프로그램을 작성하시오.

입력

자연수 n이 입력됩니다. ( 1 ≤ n ≤ 10,000 )

출력

n을 남김없이 나눌 수 있는 모든 수를 공백으로 구분하여 출력해 주세요.
'''
n = int(input())

for i in range(1, n + 1):
    if n % i == 0:
        print(i, end=" ")