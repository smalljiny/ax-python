'''
설명

현빈이는 편의점에 과자를 사러 가려고 한다.
돈이 모자랄 경우, 부모님께 부족한 돈을 받으려고 한다.

과자 한 개의 가격이 K, 사려고 하는 과자의 수는 N이다.
현재 가진 돈의 액수를 M이라고 할 때, 현빈이가 부모님께 받아야 하는 모자란 돈을 계산하는 프로그램을 작성하라.

입력

첫번째 줄에 과자의 가격 K, 과자의 수 N, 현빈이가 가진 돈의 액수 M이 공백으로 구분되어 주어진다. (1 ≤ K, N ≤ 1,000 , 1 ≤ M ≤ 100,000)

출력

현빈이가 부모님께 받아야 하는 돈의 액수를 출력한다.
만약 부모님에게 돈을 받지 않아도 된다면 0을 출력한다.
'''

K, N, M = map(int, input().split())

price = K * N

if price >= M:
    print(price - M)
else:
    print(0)
