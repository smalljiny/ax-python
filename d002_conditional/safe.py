'''
게임맵안에서 현재 힐러의 위치는 100과 200 두 군데이다.
힐러의 위치로부터 10거리 만큼 차이나는 곳을 안전지대라고 한다.
캐릭터의 위치 n이 주어졌을 때, 캐릭터가 안전지대 범위내에 있는지 판단하는 프로그램을 작성하라.

입력

첫번째 줄에 정수 n이 주어진다. (-300 <= n <= 300)

출력

만약 범위 내에 있다면 "Safe"를, 아니면 "Out"을 출력한다.
'''

n = int(input())

if abs(n - 100) <= 10 or abs(n - 200) <= 10:
    print("Safe")
else:
    print("Out")