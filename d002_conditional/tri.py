'''
설명

정삼각형은 세 변의 길이가 모두 같다.
이등변 삼각형은 두 변의 길이가 같다.
일반 삼각형은 세 변의 길이가 모두 다르다.
삼각형의 세 변의 길이가 주어졌을 때, 해당 삼각형이 어떤 삼각형인지 판단하는 프로그램을 작성하시오.

입력

첫번째 줄에 삼각형의 세 변의 길이가 공백으로 구분되어 주어진다. (1 <= 길이 <= 100)

출력

주어진 길이를 기반으로 정삼각형, 이등변 삼각형, 일반 삼각형인지를 판단하고, 출력한다.
'''

N1, N2, N3 = map(int, input().split())

if N1 == N2 == N3:
    print("정삼각형")
elif N1 == N2 or N2 == N3 or N1 == N3:
    print("이등변 삼각형")
else:
    print("일반 삼각형")