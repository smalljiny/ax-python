'''
설명

장난을 좋아하는 원숭이 두 마리가 있다.
두 원숭이는 장난을 치기 전, 둘 다 보통 같은 표정을 짓고 있다.
즉, 둘 다 웃고 있거나, 둘 다 무표정이면 장난을 칠 계획을 했다는 것이다.
원숭이 두 마리의 표정을 보고, 장난에 대비 해야 할지를 판단해보자.

입력

첫번째 줄에 원숭이 A와 B의 표정이 공백으로 구분되어 주어진다.
만약 웃고 있다면 1, 무표정이면 0이 주어진다.

출력

장난을 칠 것 같으면 "꿀꺽"을 출력한다.
장난을 치지 않을 것 같다면 "휴"를 출력한다.
'''

A, B = map(int, input().split())

if A == B:
    print("꿀꺽")
else:
    print("휴")