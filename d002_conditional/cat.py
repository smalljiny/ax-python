'''
설명

오즈는 매우 시끄럽게 냐아~ 냐아~ 하면서 우는 고양이다.
집사는 오전 7시에 출근하고, 20시에 퇴근하므로, 7시부터 20시까지는 집에 없다.
즉, 집에 있는 시간에 고양이가 울면, 집사는 매우 스트레스를 받는다.
현재 고양이가 울고 있는지에 대한 정보와 현재 시간이 주어졌을 때, 집사의 상태를 확인하라.

입력

첫번째 줄에 고양이가 울고 있다면1, 아니면 0이 주어진다.
두번째 줄에 현재 시간 T가 주어진다. (0 <= T <= 23)

출력

고양이가 집사가 집에 있는 시간에 울고있다면, "조용히 해!"를 출력한다.
그렇지 않다면 "조용하군"을 출력한다.
'''

C = int(input())
T = int(input())

if C == 1 and not (T >= 7 and T < 20):
    print("조용히 해!")
else:
    print("조용하군")
