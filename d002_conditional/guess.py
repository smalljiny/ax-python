'''
설명

당신은 친구와 생각한 숫자 맞추기 게임을 하고 있다.
친구는 두 개의 정수 A, B를 머릿속으로 생각한 후, A+B와 A-B의 값을 불러준다.
이 두 개의 값으로 A와 B의 값을 최대한 빠르게 구해서 답을 해야 한다.
이를 빠르게 구하는 프로그램을 작성하시오

입력

첫번째 줄에 두 정수의 합(A+B)과, 차(A-B)가 공백으로 구분되어 주어진다 (-10,000 <= A, B <= 10,000)
항상 답이 존재할 수 있는 A, B 값만이 주어짐이 보장된다.

출력

친구가 생각하는 숫자 A와 B를 공백으로 구분하여 출력한다.
'''

X, Y = map(int, input().split())

A = int((X + Y) / 2)
B = int(X - A)

print(A, B)