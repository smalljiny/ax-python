'''
설명

직장인은 매일 아침 출근을 해야 한다.
그들이 늦잠을 잘 수 있는 경우는 딱 2가지 경우밖에 없다.

오늘이 주말이다.
오늘은 주중이고 휴가를 쓴 날이다.
오늘이 주중인지, 휴가를 썻는지에 대한 정보가 주어졌을 때, 늦잠을 잘 수 있는지를 구하여라.

입력

첫번째 줄에 W, V가 공백으로 구분되어 주어진다. (0 <= W, V <=1)
W는 오늘이 주중이라면 1, 주말이라면 0이 주어진다.
V는 오늘이 휴가라면 1, 아니라면 0이 주어진다.

출력

오늘 늦잠을 잘 수 있다면 "늦잠자기"를 출력한다.
아니라면 "출근해야지"를 출력한다.
'''

W, V = map(int, input().split())

if W == 0 or V == 1:
    print("늦잠자기")
else:
    print("출근해야지")
