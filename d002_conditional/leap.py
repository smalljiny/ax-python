'''
설명

2월이 29일까지 있는 해를 윤년이라고 한다.
한 자연수를 입력받아 윤년인지 아닌지를 판단하는 프로그램을 작성하시오.
단, 윤년의 조건은 아래와 같다.

400의 배수이면 무조건 윤년이다.
4의 배수이며, 100의 배수가 아니면 윤년이다.
입력

연도인 정수 N이 주어집니다.

출력

조건에 맞으면 Leap를 아니면 Normal을 출력합니다.
'''

N = int(input())

if N % 400 == 0:
    print("Leap")
elif N % 4 == 0 and N % 100 != 0:
    print("Leap")
else:
    print("Normal")