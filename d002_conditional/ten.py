'''
설명

두 개의 정수 A, B가 주어졌을 때, 두개의 합이 10이거나, 둘 중 하나라도 10인지를 판단하는 프로그램을 작성하라.

입력

첫번째 줄에 정수 A, B가 공백으로 구분되어 주어진다. (0 <= A, B <= 10)

출력

만약 A와 B의 합이 10이거나, 둘 중 하나라도 10이라면 true를 출력한다.
그렇지 않다면 false를 출력한다.
'''

A, B = map(int, input().split())

if 10 in [A, B, A + B]:
    print("true")
else:
    print("false")