'''
설명

"level" 과 같이 거꾸로 읽어도 제대로 읽은 것과 같은 문장이나 낱말을 회문(回文, palindrome)이라 한다.
단어를 입력 받아 회문이면 1을 출력하고, 아니라면 0을 출력하는 프로그램을 작성하라.

입력

첫번째 줄에 회문인지 판별할 문자열 S가 주어진다.
S의 길이는 3 이상, 10 이하이다.

출력

S가 회문이라면 1, 아니면 0을 출력한다.
대소문자는 고려하지 않는다.
'''
str = input().lower()
if str == str[::-1]:
    print(1)
else:
    print(0)