'''
설명

생년월일이 주어졌을 때, 주민등록번호의 앞자리를 만들어주는 프로그램을 작성하시오.

예를 들어 생년월일이 "2003.11.3'이라면 "031103"이 주민등록번호 앞자리가 된다.

입력

첫번째 줄에 생년월일이 'YYYY.MM.DD'​형식으로 들어온다.
이 때, MM과 DD는 한 자리 혹은 두 자리 숫자이다.

출력

주민등록번호의 앞자리를 만들고, 출력형식에 맞게 출력하시오.
'''
date = input().split('.')

year = date[0][2:4]
month = int(date[1])
day = int(date[2])

print("%s%02d%02d-XXXXXXX" % (year, month, day))