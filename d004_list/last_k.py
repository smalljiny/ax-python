'''
설명

AI가 센서 데이터를 분석하고 있습니다.
센서에서는 시간 순서대로 여러 개의 측정값이 들어옵니다.
AI는 최근에 들어온 데이터 중 마지막 K개의 데이터만 확인하려고 합니다. 마지막 K개의 데이터를 출력하는 프로그램을 작성하시오.

입력

첫 번째 중에 데이터의 개수 N과 가져올 데이터의 개수 K가 주어집니다.
두 번째 줄에 N개의 정수가 주어집니다.

1 ≤ K ≤ N ≤ 100
각 데이터는 -1000 이상 1000 이하 입니다.
출력

가장 마지막에 있는 데이터부터 역순으로 출력하는 것이 아니라, 원래 순서를 유지하면서 마지막 K개의 데이터를 출력합니다.
'''
N, K = map(int, input().split())
data = list(map(int, input().split()))

print(' '.join(map(str, data[len(data)-K:])))