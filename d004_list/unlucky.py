'''
설명

예전부터 13이라는 숫자는 불길한 숫자로 여겨지고 있습니다.
n개의 숫자가 주어졌을 때, 13을 제외한 모든 숫자의 합을 구하시오.
단, 13의 바로 뒤에 오는 숫자도 불길하므로, 이 숫자도 합에서 제외합니다.

입력

첫번째 줄에 수의 개수 n이 주어집니다. (1 <= n <= 100)
다음 줄에 n개의 수가 공백으로 구분되어 주어집니다. (0 <= 수 <= 13)
13은 수열에서 여러 번 등장할 수 있습니다.

출력

불길하고 오염된 숫자들을 제외한 수열의 합을 출력합니다.
'''
data = list(map(int, input().split()))

sum = 0
for idx in range(len(data)):
    if data[idx] == 13 or (idx > 0 and data[idx - 1] == 13):
        continue
    sum += data[idx]

print(sum)